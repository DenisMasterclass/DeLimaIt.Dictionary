-- Initial schema for the configuration dictionary API.
-- Safe to run repeatedly: existing tables are left untouched.

IF OBJECT_ID(N'dbo.CONFIGURACAO_MODULO', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CONFIGURACAO_MODULO
    (
        COD_MODULO int IDENTITY(1,1) NOT NULL,
        NOM_MODULO nvarchar(100) NOT NULL,
        CONSTRAINT PK_CONFIGURACAO_MODULO PRIMARY KEY (COD_MODULO),
        CONSTRAINT UQ_CONFIGURACAO_MODULO_NOM_MODULO UNIQUE (NOM_MODULO)
    );
END;
GO

IF OBJECT_ID(N'dbo.CONFIGURACAO_PARAMETRO', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CONFIGURACAO_PARAMETRO
    (
        COD_PARAMETRO int IDENTITY(1,1) NOT NULL,
        COD_MODULO int NOT NULL,
        NOM_PARAMETRO nvarchar(100) NOT NULL,
        CONSTRAINT PK_CONFIGURACAO_PARAMETRO PRIMARY KEY (COD_PARAMETRO),
        CONSTRAINT FK_CONFIGURACAO_PARAMETRO_MODULO
            FOREIGN KEY (COD_MODULO) REFERENCES dbo.CONFIGURACAO_MODULO (COD_MODULO),
        CONSTRAINT UQ_CONFIGURACAO_PARAMETRO_MODULO_NOME UNIQUE (COD_MODULO, NOM_PARAMETRO)
    );
END;
GO

IF OBJECT_ID(N'dbo.CONFIGURACAO_CHAVE', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CONFIGURACAO_CHAVE
    (
        COD_PARAMETRO int NOT NULL,
        DSC_CHAVE nvarchar(200) NOT NULL,
        DSC_VALOR nvarchar(max) NOT NULL,
        CONSTRAINT PK_CONFIGURACAO_CHAVE PRIMARY KEY (COD_PARAMETRO, DSC_CHAVE),
        CONSTRAINT FK_CONFIGURACAO_CHAVE_PARAMETRO
            FOREIGN KEY (COD_PARAMETRO) REFERENCES dbo.CONFIGURACAO_PARAMETRO (COD_PARAMETRO)
    );
END;
GO
